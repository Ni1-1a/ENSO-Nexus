function get(id) {
  const c = CHECKLISTS[id];
  if (!c) throw new Error(`Неизвестный чек-лист: ${id}. Доступны: ${Object.keys(CHECKLISTS).join(', ')}`);
  return c;
}

function meta() {
  return Object.values(CHECKLISTS).map((c) => ({
    id: c.id, label: c.label, section: c.section, itemCount: c.items.length,
  }));
}

/**
 * Серьёзность находки «пункт чек-листа отсутствует/неполон» — детерминированное
 * правило спеки: нет пункта формы 307/пр при бюджетном финансировании → БЛОКЕР;
 * нет ключевого пункта → СУЩЕСТВЕННО; НЕПОЛНО у ключевого → СУЩЕСТВЕННО;
 * остальное → ЗАМЕЧАНИЕ.
 */
function missingSeverity(item, status, funding) {
  const budget = funding === 'бюджет' || funding === 'смешанное';
  if (status === 'НЕТ') {
    if (budget && item.form307) return 'БЛОКЕР';
    return item.key ? 'СУЩЕСТВЕННО' : 'ЗАМЕЧАНИЕ';
  }
  if (status === 'НЕПОЛНО') return item.key ? 'СУЩЕСТВЕННО' : 'ЗАМЕЧАНИЕ';
  return null;
}

/** Источник требования для находки полноты: реквизиты из данных, не из модели. */
function findingSource(item, funding) {
  const budget = funding === 'бюджет' || funding === 'смешанное';
  if (budget && item.form307) return { ...FORM307(item.form307) };
  return { ...item.source };
}

